#!/bin/bash
# Install the host's mise module and selector without overwriting local data.
set -e
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
machine="${1:-}"
case "$machine" in ''|*[!a-zA-Z0-9_-]*) echo 'Invalid machine' >&2; exit 1 ;; esac
source_file="$ROOT/per-host-config/$machine/mise.toml"
[ -f "$source_file" ] || exit 0
if [ -n "$(git -C "$ROOT" ls-files -u -- "per-host-config/$machine/mise.toml")" ]; then
    echo "Mise source has a Git conflict" >&2; exit 1
fi
config_dir="$HOME/.config/mise"
module="$config_dir/config.$machine.toml"
selector="$config_dir/miserc.local.toml"
mkdir -p "$config_dir"
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
printf '# Generated by per-host-config/setup.sh from ~/.dotfiles-machine\nenv = ["%s"]\n' "$machine" > "$tmp"
if [ -e "$selector" ] || [ -L "$selector" ]; then
    if [ ! -f "$selector" ] || ! cmp -s "$selector" "$tmp"; then
        printf 'Leaving %s unchanged: selector differs.\n' "$selector" >&2; exit 1
    fi
fi
if [ -e "$module" ] || [ -L "$module" ]; then
    if [ ! -f "$module" ] || ! cmp -s "$module" "$source_file"; then
        printf 'Leaving %s unchanged: module differs.\n' "$module" >&2; exit 1
    fi
fi
if [ "$machine" != mac-work ] || ! command -v chezmoi >/dev/null 2>&1 || ! chezmoi --version >/dev/null 2>&1; then
    [ -e "$module" ] || ln -s "$source_file" "$module"
    [ -e "$selector" ] || cp "$tmp" "$selector"
    exit 0
fi
export DOTFILES_MACHINE="$machine"
state_dir="${XDG_STATE_HOME:-$HOME/.local/state}/dotfiles"
mkdir -p "$state_dir"
chezmoi --config /dev/null --config-format toml --persistent-state "$state_dir/chezmoi.boltdb" --source "$ROOT" --destination "$HOME" apply "$module" "$selector"
