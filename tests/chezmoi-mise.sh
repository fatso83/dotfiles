#!/bin/bash
set -eu
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHEZMOI_BIN="${CHEZMOI_BIN:-$(command -v chezmoi || true)}"
[ -x "$CHEZMOI_BIN" ] || exit 1
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/bin" "$tmp/home/.config/mise"
ln -s "$CHEZMOI_BIN" "$tmp/bin/chezmoi"
export PATH="$tmp/bin:/usr/bin:/bin:/usr/sbin:/sbin" HOME="$tmp/home" XDG_STATE_HOME="$tmp/state" XDG_CONFIG_HOME="$tmp/config" XDG_DATA_HOME="$tmp/data" XDG_CACHE_HOME="$tmp/cache" GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null
ln -s "$ROOT/per-host-config/mac-work/mise.toml" "$HOME/.config/mise/config.mac-work.toml"
printf '# Generated by per-host-config/setup.sh from ~/.dotfiles-machine\nenv = ["mac-work"]\n' > "$HOME/.config/mise/miserc.local.toml"
"$ROOT/per-host-config/chezmoi-mise.sh" mac-work
"$ROOT/per-host-config/chezmoi-mise.sh" mac-work
[ -L "$HOME/.config/mise/config.mac-work.toml" ]
cmp "$HOME/.config/mise/config.mac-work.toml" "$ROOT/per-host-config/mac-work/mise.toml"
printf 'local change\n' > "$HOME/.config/mise/miserc.local.toml"
if "$ROOT/per-host-config/chezmoi-mise.sh" mac-work; then echo 'Expected selector conflict' >&2; exit 1; fi
[ "$(cat "$HOME/.config/mise/miserc.local.toml")" = 'local change' ]
echo 'chezmoi mise tests passed'
